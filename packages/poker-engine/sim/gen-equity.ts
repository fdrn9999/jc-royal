/**
 * Writes src/ai/equity-table.ts: each starting-hand class's all-in equity before the flop against one and against three
 * random hands, by Monte Carlo with a fixed seed (same output every run).
 *
 *   pnpm --filter @jc/poker-engine exec tsx sim/gen-equity.ts
 */
import { writeFileSync } from 'node:fs';
import { comboCodes, NUM_CLASSES } from '../src/ai/classes';
import { DECK_CODES, quickScore } from '../src/ai/score';
import { seeded } from './rng';

const rand = seeded(20261020);
const TRIALS_HU = 120_000;
const TRIALS_3 = 60_000;

function equity(id: number, opponents: number, trials: number): number {
  const combos = comboCodes()[id]!;
  let won = 0;
  const mine: number[] = [];
  const theirs: number[] = [];
  for (let t = 0; t < trials; t++) {
    const k = Math.floor(rand() * (combos.length / 2));
    const a = combos[k * 2]!;
    const b = combos[k * 2 + 1]!;
    const rest = DECK_CODES.filter((x) => x !== a && x !== b);
    const need = 5 + opponents * 2;
    for (let i = 0; i < need; i++) {
      const j = i + Math.floor(rand() * (rest.length - i));
      const x = rest[i]!;
      rest[i] = rest[j]!;
      rest[j] = x;
    }
    mine.length = 0;
    mine.push(a, b, rest[0]!, rest[1]!, rest[2]!, rest[3]!, rest[4]!);
    const my = quickScore(mine);
    let ties = 0;
    let lost = false;
    for (let o = 0; o < opponents && !lost; o++) {
      theirs.length = 0;
      theirs.push(rest[5 + o * 2]!, rest[6 + o * 2]!, rest[0]!, rest[1]!, rest[2]!, rest[3]!, rest[4]!);
      const s = quickScore(theirs);
      if (s > my) lost = true;
      else if (s === my) ties++;
    }
    if (!lost) won += 1 / (ties + 1);
  }
  return won / trials;
}

const hu: number[] = [];
const three: number[] = [];
for (let id = 0; id < NUM_CLASSES; id++) {
  hu.push(Math.round(equity(id, 1, TRIALS_HU) * 10000));
  three.push(Math.round(equity(id, 3, TRIALS_3) * 10000));
}
const body = `/**
 * Generated by sim/gen-equity.ts (fixed seed; do not edit by hand): each starting-hand class's all-in equity before the
 * flop, in hundredths of a percent, against one random hand (${TRIALS_HU.toLocaleString('en')} deals a class) and
 * against three (${TRIALS_3.toLocaleString('en')} deals). Index = class id (classes.ts).
 */
export const EQUITY_VS_ONE: readonly number[] = [${hu.join(', ')}];
export const EQUITY_VS_THREE: readonly number[] = [${three.join(', ')}];
`;
writeFileSync(new URL('../src/ai/equity-table.ts', import.meta.url), body);
console.log('written', hu.slice(0, 3), three.slice(0, 3));
