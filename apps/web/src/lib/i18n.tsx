export type Dict = Record<keyof typeof ko, string>;

export type MsgKey = keyof typeof ko;
export type Locale = 'ko' | 'en';

/**
 * English is its own chunk (i18n-en.ts), loaded when someone chooses it, so the Korean default never downloads it
 * (tests/bundle-check.mjs). Until it has loaded, or if it cannot load, the text stays Korean.
 */
let en: Dict | undefined;
export function loadLocale(l: Locale): Promise<void> {
  if (l === 'ko' || en) return Promise.resolve();
  return import('./i18n-en').then((m) => {
    en = m.en;
  });
}
const translator = (l: Locale) => createTranslator<Dict>({ ko, en: en ?? ko })(l === 'en' && en ? 'en' : 'ko');

interface I18nCtx {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: MsgKey, vars?: Record<string, string | number>) => string;
  /** Translate an API/WS error code, falling back to a generic message. */
  err: (code: string | undefined | null) => string;
}

const Ctx = createContext<I18nCtx | null>(null);

/** A saved choice first; otherwise the language a shared link asks for (?lang=en, as its preview was), else Korean. */
export function initialLocale(): Locale {
  try {
    const saved = localStorage.getItem('jc.locale');
    if (saved === 'ko' || saved === 'en') return saved;
  } catch {
    /* ignore */
  }
  const asked = new URLSearchParams(window.location.search).get('lang');
  return asked === 'en' ? 'en' : 'ko';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  // main.tsx loads the first language before rendering; English that failed to load shows as Korean.
  const [locale, setLocaleState] = useState<Locale>(() => (initialLocale() === 'en' && en ? 'en' : 'ko'));
  // index.html says ko; a saved or asked-for English has to say so too (screen readers, translation prompts).
  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);
  // The latest choice wins when an earlier one is still loading.
  const wanted = useRef<Locale | null>(null);
  const setLocale = useCallback((l: Locale) => {
    wanted.current = l;
    try {
      localStorage.setItem('jc.locale', l);
    } catch {
      /* ignore */
    }
    loadLocale(l).then(
      () => {
        if (wanted.current === l) setLocaleState(l);
      },
      () => {
        /* stays in the current language; the next choice tries again */
      },
    );
  }, []);
  const value = useMemo<I18nCtx>(() => {
    const t = translator(locale);
    return {
      locale,
      setLocale,
      t,
      err: (code) => {
        const key = `err.${code ?? ''}` as MsgKey;
        return key in ko ? t(key) : t('common.error');
      },
    };
  }, [locale, setLocale]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const v = useContext(Ctx);
  if (!v) throw new Error('I18nProvider missing');
  return v;
}
