const subs = new Set<() => void>();
export function setLocale(l: 'ko' | 'en') {
  locale = l;
  try {
    localStorage.setItem('jc.admin.locale', l);
  } catch {
    /* ignore */
  }
  subs.forEach((f) => f());
}
export function useT() {
  const l = useSyncExternalStore(
    (cb) => {
      subs.add(cb);
      return () => subs.delete(cb);
    },
    () => locale,
  );
  return { t: make(l), locale: l };
}
